const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
let browser;
(async () => {
  const root = path.resolve(__dirname, '..');
  const access = JSON.parse(fs.readFileSync(path.join(root, 'private/deployment-access.json'), 'utf8'));
  browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('https://orange.lingzidev.com/admin');
  await page.getByRole('heading', { name: '欢迎回到管理中心' }).waitFor();
  assert.equal(await page.locator('.stat-card').count(), 0);
  await page.screenshot({ path: path.join(root, 'output/live-admin-login.png') });
  await page.getByLabel('管理密码').fill(access.admin_password);
  await page.getByRole('button', { name: '登录管理中心' }).click();
  await page.locator('.platform-grid b').first().waitFor();
  await page.screenshot({ path: path.join(root, 'output/live-admin.png'), fullPage: true });
  await page.getByRole('button', { name: '推送策略', exact: true }).click();
  await page.getByLabel('欢迎语', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(root, 'output/live-strategy.png') });
  await page.getByRole('button', { name: '退出', exact: true }).click();
  await page.getByRole('heading', { name: '欢迎回到管理中心' }).waitFor();
  assert.equal(await page.locator('.stat-card').count(), 0);
  await page.goto('https://orange.lingzidev.com/');
  await page.getByRole('button', { name: '登录领福利', exact: true }).waitFor();
  await page.getByRole('button', { name: '登录领福利', exact: true }).click();
  assert.equal(await page.getByLabel('手机号', { exact: true }).inputValue(), '');
  assert.equal(await page.getByLabel('密码', { exact: true }).inputValue(), '');
  await page.getByLabel('手机号', { exact: true }).fill(access.app_phone);
  await page.getByLabel('密码', { exact: true }).fill(access.app_password);
  await page.locator('.auth-sheet').getByRole('button', { name: '登录', exact: true }).click();
  await page.locator('.auth-sheet').waitFor({ state: 'hidden' });
  await page.locator('[data-event-kind="product"]').first().waitFor({ timeout: 15000 });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(600);
  await page.screenshot({ path: path.join(root, 'output/live-mobile-hall.png') });
  await page.goto('https://orange-api.lingzidev.com/privacy');
  await page.getByRole('heading', { name: '隐私政策', exact: true }).waitFor();
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(root, 'output/live-web-verification.json'), JSON.stringify({ passed: true, realAdminLogin: true, realAccountLogin: true, realSse: true, publicPrivacy: true, runtimeErrors: errors }, null, 2));
  console.log('PASS real HTTPS admin login, account login, SSE, policy; no runtime errors');
  await browser.close();
})().catch(async error => { console.error(error); if (browser) await browser.close(); process.exitCode = 1; });
